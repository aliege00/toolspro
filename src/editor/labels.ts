const dictionaries = { tr, en };

export function editorText(lang: "tr" | "en", key: EditorKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function useEditorT() {
  const { lang } = useI18n();
  return (key: EditorKey, vars?: Record<string, string | number>) =>
    editorText(lang, key, vars);
}

export type { EditorKey };
